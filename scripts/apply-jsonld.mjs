#!/usr/bin/env node
// Injects structured data into the hub and every tool page, between
// JSONLD-START/END markers (strip-then-reinsert, so reruns never duplicate).
//
// Why: Google crawled the hub on 28 May 2026 and filed it "Crawled - currently
// not indexed". Structured data states plainly what each page is - a free,
// browser-only tool, and the FAQ it answers - which is exactly the machine-legible
// signal that verdict is asking for. Every tool page already carries a real
// <h2> + <details> FAQ, so FAQPage describes content that genuinely exists.
//
// Deliberately NOT emitted: aggregateRating or review. Google REQUIRES one of them
// for the Software App rich result, so these pages are not eligible for the star
// snippet. That is the correct outcome: there are no ratings, and inventing them is
// both a policy violation and a lie. The markup still earns its place as a
// comprehension signal. If a real rating mechanism ever ships, revisit this.
//
// Run: node scripts/apply-jsonld.mjs   (or npm run build)

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BASE = 'https://tools.muhammadhassaanjaved.com/';
const AUTHOR_URL = 'https://muhammadhassaanjaved.com/';
const START = '<!-- JSONLD-START (generated by scripts/apply-jsonld.mjs) -->';
const END = '<!-- JSONLD-END -->';
const BLOCK = new RegExp(`[ \\t]*${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}\\n?`, 'g');
const SKIP = new Set(['scripts', 'node_modules', '.git', '.github']);
const posix = (p) => p.split('\\').join('/');

const tools = JSON.parse(readFileSync(join(ROOT, 'tools.json'), 'utf8'));
const byUrl = new Map(tools.map((t) => [t.url, t]));

const CATEGORY_TO_SCHEMA = {
  text: 'UtilitiesApplication',
  design: 'DesignApplication',
  media: 'MultimediaApplication',
  security: 'SecurityApplication',
  time: 'UtilitiesApplication',
};

const PERSON = {
  '@type': 'Person',
  name: 'Muhammad Hassaan Javed',
  url: AUTHOR_URL,
};

const stripTags = (s) => s
  .replace(/<[^>]+>/g, ' ')
  .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'")
  .replace(/\s+/g, ' ')
  .trim();

// Pull the on-page FAQ so the markup describes content a visitor actually sees.
function faqFrom(html) {
  const out = [];
  for (const m of html.matchAll(/<details[^>]*>([\s\S]*?)<\/details>/g)) {
    const inner = m[1];
    if (/id="tool-feedback-form"/.test(inner)) continue; // the feedback form is a <details> too
    const q = inner.match(/<summary[^>]*>([\s\S]*?)<\/summary>/);
    if (!q) continue;
    const question = stripTags(q[1]);
    const answer = stripTags(inner.replace(/<summary[^>]*>[\s\S]*?<\/summary>/, ''));
    if (!question || !answer) continue;
    out.push({
      '@type': 'Question',
      name: question,
      acceptedAnswer: { '@type': 'Answer', text: answer },
    });
  }
  return out;
}

function graphFor(rel, html) {
  const url = BASE + rel;
  const title = (html.match(/<title>([^<]*)<\/title>/) || [, ''])[1].trim();
  const desc = (html.match(/<meta name="description" content="([^"]*)"/) || [, ''])[1].trim();
  const graph = [];

  if (rel === '') {
    graph.push({
      '@type': 'CollectionPage',
      '@id': url + '#page',
      url,
      name: title,
      description: desc,
      isPartOf: { '@type': 'WebSite', '@id': BASE + '#website', url: BASE, name: 'Web Utility Tools by CRUSHER', publisher: PERSON },
      about: PERSON,
      mainEntity: {
        '@type': 'ItemList',
        numberOfItems: tools.length,
        itemListElement: tools.map((t, i) => ({
          '@type': 'ListItem',
          position: i + 1,
          url: t.url,
          name: t.name,
        })),
      },
    });
    return graph;
  }

  const tool = byUrl.get(url);
  const name = tool ? tool.name : title.split(/\s+[-|]\s+/)[0].trim();
  const app = {
    // WebApplication, a SoftwareApplication subtype: accurate for a browser-only
    // tool, and browserRequirements is properly defined on it.
    '@type': 'WebApplication',
    '@id': url + '#app',
    name,
    url,
    description: tool ? tool.description : desc,
    applicationCategory: CATEGORY_TO_SCHEMA[tool && tool.category] || 'UtilitiesApplication',
    operatingSystem: 'Any',
    browserRequirements: 'Requires JavaScript. Runs entirely in the browser.',
    isAccessibleForFree: true,
    offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
    author: PERSON,
    publisher: PERSON,
    isPartOf: { '@type': 'WebSite', '@id': BASE + '#website' },
  };
  graph.push(app);

  graph.push({
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Web Utility Tools', item: BASE },
      { '@type': 'ListItem', position: 2, name, item: url },
    ],
  });

  const faq = faqFrom(html);
  if (faq.length) graph.push({ '@type': 'FAQPage', '@id': url + '#faq', mainEntity: faq });
  return graph;
}

const pages = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir)) {
    if (SKIP.has(entry)) continue;
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    if (entry === 'index.html') pages.push(p);
  }
};
walk(ROOT);

let written = 0, faqPages = 0, problems = [];
for (const file of pages) {
  const rel = posix(relative(ROOT, file)).replace(/index\.html$/, '');
  let html = readFileSync(file, 'utf8');
  const graph = graphFor(rel, html);
  if (graph.some((n) => n['@type'] === 'FAQPage')) faqPages += 1;

  const json = JSON.stringify({ '@context': 'https://schema.org', '@graph': graph }, null, 2);
  // Guard: JSON-LD lives in a <script> block, so a literal "</script>" inside any
  // string would close it early.
  if (json.includes('</script')) { problems.push(rel + ': content would close the script tag'); continue; }
  const block = `${START}\n<script type="application/ld+json">\n${json}\n</script>\n${END}`;

  html = html.replace(BLOCK, '');
  if (!html.includes('</head>')) { problems.push(rel + ': no </head> anchor'); continue; }
  html = html.replace('</head>', block + '\n</head>');
  writeFileSync(file, html);
  written += 1;
}

if (problems.length) {
  for (const p of problems) console.error('[apply-jsonld] ' + p);
  process.exit(1);
}
console.log(`[apply-jsonld] structured data written to ${written} page(s); ${faqPages} carry an FAQPage`);
